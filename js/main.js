const LANG_KEY = "gisda-lang";

function currentLang() {
  return "en";
}

function applyLang(lang) {
  document.documentElement.lang = lang === "en" ? "en" : "zh-CN";
  document.title = I18N[lang]["meta.title"];

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (I18N[lang][key] != null) el.innerHTML = I18N[lang][key];
  });

  document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
    const key = el.getAttribute("data-i18n-alt");
    if (I18N[lang][key] != null) el.setAttribute("alt", I18N[lang][key]);
  });

}

// 滚动入场动效
const revealTargets = [
  ".section-head", ".display", ".lead", ".stat", ".rule-block", ".result",
  ".partner", ".sponsor-card", ".g", ".why", ".mascot-media", ".apparel",
  ".rp", ".ag", ".roadmap li", ".school-cell", ".hero-figure", ".hero-found",
  ".rules-posters"
];

function setupReveal() {
  const els = document.querySelectorAll(revealTargets.join(","));
  els.forEach((el) => el.classList.add("reveal"));

  if (!("IntersectionObserver" in window)) {
    els.forEach((el) => el.classList.add("in"));
    return;
  }
  const io = new IntersectionObserver(
    (entries) => {
      entries.forEach((e) => {
        if (e.isIntersecting) {
          e.target.classList.add("in");
          io.unobserve(e.target);
        }
      });
    },
    { threshold: 0.12, rootMargin: "0px 0px -8% 0px" }
  );
  els.forEach((el) => io.observe(el));
}

// 顶栏滚动强化
function setupTopbar() {
  const bar = document.getElementById("topbar");
  const onScroll = () => {
    bar.classList.toggle("scrolled", window.scrollY > 12);
  };
  window.addEventListener("scroll", onScroll, { passive: true });
  onScroll();
}

// 首屏以外的图片懒加载
document.querySelectorAll("img").forEach((img) => {
  if (!img.closest(".hero") && !img.closest(".topbar")) img.loading = "lazy";
});

// 初始化
applyLang(currentLang());
setupReveal();
setupTopbar();
